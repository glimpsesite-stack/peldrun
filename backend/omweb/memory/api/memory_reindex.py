# backend/omweb/memory/api/memory_reindex.py
"""
PELDRUN Memory Platform - Phase 4: Embedding Reindex HTTP Router.

Single endpoint (``POST /api/memory/reindex``) that enqueues
embedding jobs for memories that need one. Two usage modes:

    * **Full reindex** (``memory_ids=null``): iterate every ACTIVE
      memory that lacks an embedding under the current model.
      Used after enabling embedding for the first time, after
      switching models, or after a vec0 dimension rebuild.

    * **Selective reindex** (``memory_ids=[...]``): enqueue only
      for the provided ids. Used by the operator to force a
      refresh for specific entries after editing their content.

Idempotency
-----------

The endpoint is IDEMPOTENT by design:

    * A memory that already has an embedding row at
      ``(memory_id, model_id, model_version, content_version)``
      is SKIPPED (``skipped`` counter). Re-clicking the button
      does NOT waste API calls.

    * A memory whose ``EmbeddingJob`` is already pending (from a
      previous click or a concurrent request) also counts as
      SKIPPED. The ``EmbeddingOutbox.enqueue`` method raises
      ``DuplicateJobError`` for those rows; we translate the
      exception into ``skipped += 1`` and continue.

Both skip paths contribute to the same counter -- callers who
want to distinguish "already embedded" from "job already
pending" would need to read ``memory_embeddings`` and
``memory_embedding_jobs`` directly. Phase 4 does not require
the distinction; the operator just wants to know "did this
button do work or not?".

Failure modes
-------------

The endpoint returns 503 (service unavailable) for every
"config not ready" condition -- the operator's intent is valid
but the subsystem is not yet in a state to honor it:

    * **embedding_not_enabled** -- ``embedding.enabled=False``.
    * **model_key_not_set** -- enabled but no model selected.
    * **model_key_not_in_snapshot** -- the configured model_key
      does not match any model in the metadata cache. Usually
      because the model was removed from the vault after being
      selected.

A 500 (internal error) is reserved for actual failures (SQLite
corruption, unexpected exceptions). The message names the
exception class so logs can be grepped.

A 422 (validation error) is generated by FastAPI/Pydantic
BEFORE the handler runs, for malformed bodies (e.g. more than
``_MAX_MEMORY_IDS_PER_REQUEST`` ids, or empty ``memory_ids``
list).

Read-only vs mutation
---------------------

This endpoint MUTATES ``memory_embedding_jobs`` (enqueues new
rows). It does NOT touch ``memories`` or
``memory_embeddings`` -- the worker is the only component that
writes vectors, and only after processing a job. This
distinction matters for audit purposes: calling the endpoint
N times produces at most N enqueues, never N writes.
"""

from __future__ import annotations

import logging
import sqlite3
from pathlib import Path
from typing import List, Optional

from fastapi import APIRouter, status as http_status
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, Field, field_validator

from omweb.memory import get_memory_service
from omweb.memory.jobs.models import EmbeddingJob
from omweb.memory.jobs.outbox import (
    DuplicateJobError,
    EmbeddingOutbox,
)
from omweb.memory.manager.snapshot_builder import (
    build_embedding_model_snapshot,
)


logger = logging.getLogger("omweb.memory.api.reindex")


router = APIRouter()


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------


_MAX_MEMORY_IDS_PER_REQUEST: int = 1_000
"""Upper bound on explicit ``memory_ids``.

Protects the endpoint from a caller that accidentally passes the
entire table as a list. Bulk reindex should use ``memory_ids=null``
(the "all active" path) which reads ids directly from SQL instead
of accepting them via HTTP -- O(1) memory in the server process.
"""


# ---------------------------------------------------------------------------
# Request body
# ---------------------------------------------------------------------------


class _ReindexBody(BaseModel):
    """Body of ``POST /api/memory/reindex``.

    All fields optional; ``{}`` is a valid body (full reindex of
    active memories under the current model).
    """

    model_config = ConfigDict(extra="forbid")

    memory_ids: Optional[List[str]] = Field(
        default=None,
        description=(
            "Specific memory ids to (re)enqueue. When ``None`` "
            "(default), the endpoint reindexes ALL active "
            "memories that lack an embedding under the current "
            "model. When a list is given, only those ids are "
            "checked and enqueued. Ids that do not exist or "
            "already have embeddings are counted as ``skipped`` "
            "in the response."
        ),
    )
    content_version: int = Field(
        default=1,
        ge=1,
        description=(
            "Content version of the embedding to produce. "
            "Phase 4 uses 1 exclusively. Phase 5 consolidation "
            "increments this when rewriting memory content -- "
            "passing a higher value forces a fresh embedding "
            "even when one already exists at version 1."
        ),
    )

    @field_validator("memory_ids", mode="after")
    @classmethod
    def _validate_memory_ids(
        cls, v: Optional[List[str]]
    ) -> Optional[List[str]]:
        """Reject empty lists, oversized batches, and duplicates.

        Deduplication is done HERE (not downstream) so the
        response counts are exactly what the caller sees.
        Duplicate ids in the input would otherwise inflate
        ``skipped`` by the number of duplicates per id -- a
        confusing count that hides the real state.
        """
        if v is None:
            return None
        if not isinstance(v, list):
            raise ValueError(
                f"memory_ids must be a list or null, got "
                f"{type(v).__name__}"
            )
        if not v:
            raise ValueError(
                "memory_ids must not be empty; omit the field "
                "or pass null for a full reindex"
            )
        if len(v) > _MAX_MEMORY_IDS_PER_REQUEST:
            raise ValueError(
                f"memory_ids has {len(v)} entries; maximum is "
                f"{_MAX_MEMORY_IDS_PER_REQUEST}. For larger "
                f"batches, omit memory_ids (full reindex) and "
                f"let the server stream ids from SQL."
            )
        seen: set = set()
        deduped: List[str] = []
        for mid in v:
            if not isinstance(mid, str) or not mid.strip():
                raise ValueError(
                    f"memory_ids entries must be non-empty "
                    f"strings, got {mid!r}"
                )
            clean = mid.strip()
            if clean in seen:
                continue
            seen.add(clean)
            deduped.append(clean)
        return deduped


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _error_response(
    *,
    status_code: int,
    error: str,
    message: str,
) -> JSONResponse:
    """Uniform error envelope for every failure path."""
    return JSONResponse(
        status_code=status_code,
        content={
            "ok": False,
            "error": error,
            "message": message,
        },
    )


def _load_active_memory_ids(db_path: Path) -> List[str]:
    """Return the ids of all ACTIVE memories in the database.

    Runs on a dedicated connection (opened + closed in this call)
    so that the endpoint never holds a long-lived read lock.
    WAL permits concurrent reads with the writer connections
    used by the outbox.

    The WHERE clause matches the repository's "retrievable"
    rule: status is ACTIVE and ``expires_at`` is either NULL
    or in the future. Non-retrievable memories do not need
    embeddings.
    """
    conn = sqlite3.connect(str(db_path), timeout=30.0)
    try:
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA busy_timeout = 30000")
        rows = conn.execute(
            """
            SELECT memory_id FROM memories
            WHERE status = 'active'
              AND (expires_at IS NULL
                   OR expires_at > strftime('%s','now'))
            """
        ).fetchall()
        return [r["memory_id"] for r in rows]
    finally:
        conn.close()


def _has_embedding(
    db_path: Path,
    memory_id: str,
    model_id: str,
    model_version: str,
    content_version: int,
) -> bool:
    """Return True when a matching embedding row already exists."""
    conn = sqlite3.connect(str(db_path), timeout=30.0)
    try:
        conn.execute("PRAGMA busy_timeout = 30000")
        row = conn.execute(
            """
            SELECT 1 FROM memory_embeddings
            WHERE memory_id = ?
              AND model_id = ?
              AND model_version = ?
              AND content_version = ?
            LIMIT 1
            """,
            (memory_id, model_id, model_version, content_version),
        ).fetchone()
        return row is not None
    finally:
        conn.close()


