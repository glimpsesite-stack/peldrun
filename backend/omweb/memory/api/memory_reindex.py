# Endpoint
# ---------------------------------------------------------------------------


@router.post(
    "/reindex",
    summary="Enqueue embedding jobs for existing memories",
    response_model=None,
)
async def reindex_endpoint(body: _ReindexBody) -> JSONResponse:
    """Enqueue embedding jobs for memories that need one.

    See the module docstring for the idempotency guarantee, the
    failure modes, and the response field semantics.
    """
    service = get_memory_service()

    # ---- 1. Config gates ----------------------------------
    embedding_settings = service.settings.embedding
    if not embedding_settings.enabled:
        return _error_response(
            status_code=http_status.HTTP_503_SERVICE_UNAVAILABLE,
            error="embedding_not_enabled",
            message=(
                "Embedding subsystem is disabled. Enable it via "
                "PATCH /api/memory/settings "
                "(embedding.enabled=true) before reindexing."
            ),
        )
    model_key = embedding_settings.model_key
    if not model_key:
        return _error_response(
            status_code=http_status.HTTP_503_SERVICE_UNAVAILABLE,
            error="model_key_not_set",
            message=(
                "Embedding is enabled but no model_key is "
                "configured. Select an embedding model via "
                "PATCH /api/memory/settings "
                "(embedding.model_key=...)."
            ),
        )

    # ---- 2. Resolve model_key to concrete credentials ------
    try:
        snapshot = build_embedding_model_snapshot()
    except Exception as exc:
        logger.exception(
            "reindex: snapshot build failed: %s", exc
        )
        return _error_response(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            error="internal_error",
            message=(
                f"Could not build embedding model snapshot: "
                f"{type(exc).__name__}: {exc}"
            ),
        )

    resolved = snapshot.get(model_key)
    if resolved is None:
        return _error_response(
            status_code=http_status.HTTP_503_SERVICE_UNAVAILABLE,
            error="model_key_not_in_snapshot",
            message=(
                f"Configured model_key {model_key!r} does not "
                f"resolve to any model in the metadata cache. "
                f"Re-select the embedding model via "
                f"PATCH /api/memory/settings."
            ),
        )

    # ---- 3. Locate the DB ----------------------------------
    #
    # ``_lifecycle.db_path`` is the repository-internal
    # accessor for the memory DB path. Both
    # ``MemoryService.__init__`` and ``_initialize_extraction``
    # read it via the same attribute -- this endpoint follows
    # the established pattern rather than introducing a new
    # public property (which would be a larger change to a
    # file that Phase 4 does not otherwise touch).
    try:
        db_path = service._lifecycle.db_path
    except Exception as exc:
        logger.exception(
            "reindex: db_path unavailable: %s", exc
        )
        return _error_response(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            error="internal_error",
            message=(
                f"Memory DB path is not accessible: "
                f"{type(exc).__name__}: {exc}"
            ),
        )
    if db_path is None:
        return _error_response(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            error="internal_error",
            message="Memory DB path is None.",
        )

    # ---- 4. Determine the id list --------------------------
    if body.memory_ids is not None:
        memory_ids: List[str] = list(body.memory_ids)
    else:
        try:
            memory_ids = _load_active_memory_ids(db_path)
        except Exception as exc:
            logger.exception(
                "reindex: could not list active memories: %s",
                exc,
            )
            return _error_response(
                status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
                error="internal_error",
                message=(
                    f"Could not enumerate active memories: "
                    f"{type(exc).__name__}: {exc}"
                ),
            )

    # ---- 5. Enqueue jobs, skipping ones that already exist --
    outbox = EmbeddingOutbox(db_path)
    try:
        await outbox.open()
    except Exception as exc:
        logger.exception(
            "reindex: outbox open failed: %s", exc
        )
        return _error_response(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            error="internal_error",
            message=(
                f"Could not open the embedding outbox: "
                f"{type(exc).__name__}: {exc}"
            ),
        )

    enqueued = 0
    skipped = 0
    try:
        for memory_id in memory_ids:
            # Skip memories that already have the embedding.
            try:
                already = _has_embedding(
                    db_path,
                    memory_id,
                    resolved.model_id,
                    resolved.model_version,
                    body.content_version,
                )
            except Exception as exc:
                logger.warning(
                    "reindex: embedding existence check failed "
                    "for memory_id=%r: %s -- skipping",
                    memory_id,
                    exc,
                )
                skipped += 1
                continue

            if already:
                skipped += 1
                continue

            # Build + enqueue.
            try:
                job = EmbeddingJob(
                    memory_id=memory_id,
                    model_id=resolved.model_id,
                    model_version=resolved.model_version,
                    content_version=body.content_version,
                )
                await outbox.enqueue(job)
                enqueued += 1
            except DuplicateJobError:
                # Race with a concurrent enqueue -- treat as
                # "already pending", which is exactly the
                # behavior the caller wants.
                skipped += 1
            except Exception as exc:
                logger.warning(
                    "reindex: enqueue failed for memory_id=%r: "
                    "%s: %s -- skipping",
                    memory_id,
                    type(exc).__name__,
                    exc,
                )
                skipped += 1
    finally:
        try:
            await outbox.close()
        except Exception as exc:
            logger.warning(
                "reindex: outbox close failed (non-fatal): %s",
                exc,
            )

    # ---- 6. Response --------------------------------------
    logger.info(
        "reindex: model_key=%r model_id=%r total=%d "
        "enqueued=%d skipped=%d",
        model_key,
        resolved.model_id,
        len(memory_ids),
        enqueued,
        skipped,
    )
    return JSONResponse(
        status_code=http_status.HTTP_200_OK,
        content={
            "ok": True,
            "model_key": model_key,
            "model_id": resolved.model_id,
            "model_version": resolved.model_version,
            "content_version": body.content_version,
            "total_candidates": len(memory_ids),
            "enqueued": enqueued,
            "skipped": skipped,
        },
    )


